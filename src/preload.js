const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getBuild: () => ipcRenderer.invoke('app:build'),
  licenseStatus: () => ipcRenderer.invoke('license:status'),
  licenseActivate: (key) => ipcRenderer.invoke('license:activate', key),
  logDebug: (msg) => ipcRenderer.invoke('debug:log', msg),
  defaultSshKey: () => ipcRenderer.invoke('ssh:default-key'),
  getSetting: (key) => ipcRenderer.invoke('settings:get', key),
  setSetting: (key, value) => ipcRenderer.invoke('settings:set', key, value),
  addHistoryPoint: (id, point) => ipcRenderer.invoke('server:hist-add', { id, point }),
  newsList: () => ipcRenderer.invoke('news:list'),
  newsAdd: (item) => ipcRenderer.invoke('news:add', item),
  newsClear: () => ipcRenderer.invoke('news:clear'),
  listServers: () => ipcRenderer.invoke('servers:list'),
  saveServer: (server) => ipcRenderer.invoke('servers:save', server),
  deleteServer: (id) => ipcRenderer.invoke('servers:delete', id),
  testServer: (server) => ipcRenderer.invoke('server:test', server),
  getStatus: (id) => ipcRenderer.invoke('server:status', id),
  getHistory: (id) => ipcRenderer.invoke('server:history', id),
  sendCommand: (id, command) => ipcRenderer.invoke('server:command', { id, command }),
  startLogs: (id) => ipcRenderer.invoke('server:logs:start', id),
  sshExec: (id, command) => ipcRenderer.invoke('server:ssh-exec', { id, command }),
  stopLogs: (id) => ipcRenderer.invoke('server:logs:stop', id),
  onLogs: (cb) => ipcRenderer.on('server:logs', (event, data) => cb(data)),
  pluginsSearch: (args) => ipcRenderer.invoke('plugins:search', args),
  pluginsInstall: (args) => ipcRenderer.invoke('plugins:install', args),
  pluginsDownload: (args) => ipcRenderer.invoke('plugins:download', args),
  pluginsInstalled: (id) => ipcRenderer.invoke('plugins:installed', id),
  openUrl: (url) => ipcRenderer.invoke('app:open-url', url),
  autoList: (id) => ipcRenderer.invoke('auto:list', id),
  autoSave: (args) => ipcRenderer.invoke('auto:save', args),
  autoDeploy: (args) => ipcRenderer.invoke('auto:deploy', args),
  autoTest: (args) => ipcRenderer.invoke('auto:test', args),
  autoStatus: (id) => ipcRenderer.invoke('auto:status', id),
  autoLog: (args) => ipcRenderer.invoke('auto:log', args),
  autoClean: (args) => ipcRenderer.invoke('auto:clean', args),
});
